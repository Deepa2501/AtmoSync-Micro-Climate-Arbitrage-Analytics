-- AtmoSync: Raw IoT Sensor Data Table

CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW.RAW_SENSOR_DATA (
    SENSOR_ID VARCHAR(50) NOT NULL,
    LOCATION VARCHAR(100),
    TEMPERATURE FLOAT,
    HUMIDITY FLOAT,
    VIBRATION FLOAT,
    EVENT_TIMESTAMP TIMESTAMP_TZ,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
