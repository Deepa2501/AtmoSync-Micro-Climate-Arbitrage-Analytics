
-- AtmoSync: Raw Commodity Prices Table

CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW.RAW_COMMODITY_PRICES (
    DATE DATE,
    AVERAGE_PRICE FLOAT,
    TOTAL_VOLUME FLOAT,
    PLU_4046 FLOAT,
    PLU_4225 FLOAT,
    PLU_4770 FLOAT,
    TOTAL_BAGS FLOAT,
    SMALL_BAGS FLOAT,
    LARGE_BAGS FLOAT,
    XLARGE_BAGS FLOAT,
    TYPE VARCHAR(50),
    YEAR NUMBER(4,0),
    REGION VARCHAR(100),

    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
